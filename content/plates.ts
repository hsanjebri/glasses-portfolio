import type { FrameShape } from './types'

/** A point on a photograph, in percent of its width (x) and height (y). */
export type Pt = readonly [x: number, y: number]

/**
 * Where the frame and the lenses sit in each shape's photograph, so the
 * configurator can recolour the frame and tint the lenses on the photo itself.
 * Outlines are smoothed into curves when drawn.
 *
 * PLACEHOLDER — traced on the stand-in Unsplash photos in content/photos.ts.
 * Retrace when the shop's own product shots replace them.
 */
export interface Plate {
  /** Inner edge of each lens: where the lens tint goes, and what recolouring leaves alone. */
  lenses: readonly [Pt[], Pt[]]
  /** Outer edge of each rim. These set the framing of the shot. */
  rims: readonly [Pt[], Pt[]]
  /** Bridge, endpieces and whatever temples are in view. */
  parts: Pt[][]
  /**
   * How dark a pixel must be (luminance, 0–1) to count as frame when it is
   * repainted. null for a light metal frame against a light background, which
   * is toned instead — its colour shifted, its shading kept.
   */
  key: number | null
  /** The photo's lenses are already tinted, so clear lenses have to be lightened. */
  sunLenses?: boolean
}

const mirror = (pts: Pt[], axis: number): Pt[] => pts.map(([x, y]) => [+(axis - x).toFixed(2), y] as const)

/** Pushes an outline outwards from its centre by d, for a thin wire rim around a traced lens. */
const grow = (pts: Pt[], d: number): Pt[] => {
  const cx = pts.reduce((s, p) => s + p[0], 0) / pts.length
  const cy = pts.reduce((s, p) => s + p[1], 0) / pts.length
  return pts.map(([x, y]) => {
    const len = Math.hypot(x - cx, y - cy) || 1
    return [+(x + ((x - cx) / len) * d).toFixed(2), +(y + ((y - cy) / len) * d).toFixed(2)] as const
  })
}

